export function translateValue(value: string, language: "ms" | "en"): string {
  if (language === "en") return value;
  const normalized = value.replace(/\s+/g, " ").trim();
  const translated = msTranslations[normalized] ?? msAttributeTranslations[normalized];
  if (translated !== undefined) {
    const leading = value.match(/^\s*/)?.[0] ?? "";
    const trailing = value.match(/\s*$/)?.[0] ?? "";
    return `${leading}${translated}${trailing}`;
  }

  // Localize dates rendered by existing server components, e.g. "09 Oct 2026".
  if (/^\d{1,2}\s+[A-Za-z]{3}\s+\d{4}$/.test(normalized)) {
    const monthMap: Record<string, string> = {
      Jan: "Jan", Feb: "Feb", Mar: "Mac", Apr: "Apr", May: "Mei", Jun: "Jun",
      Jul: "Jul", Aug: "Ogo", Sep: "Sep", Oct: "Okt", Nov: "Nov", Dec: "Dis"
    };
    return value.replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b/g, (month) => monthMap[month]);
  }
  return value;
}


